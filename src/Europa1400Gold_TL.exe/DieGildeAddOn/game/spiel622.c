{
	short* ent;
	int total;

	total = 0;
	ent = gm_ff_Objekt(entity, 1, 4, 9);
	if (ent != (short*) 0) {
		do {
			if ((short) g_entity_slot_table[(obj_type & 0xff) * 189] == *ent) {
				total = total + *(int*) (ent + 7);
			}
			ent = gm_NextEntityQueryMatch();
		} while (ent != (short*) 0);
	}
	return total;
}

