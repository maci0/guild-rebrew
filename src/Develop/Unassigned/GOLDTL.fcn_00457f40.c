/* Terrain patch builder (one-cell step): locks a vertex buffer (24-byte
 * vertices) and an index buffer, fills both from the height grid, and
 * skips triangles whose corner heights differ by more than a scale-derived
 * threshold.  Returns the number of triangles written. */

#include <stdlib.h>

typedef int (__stdcall *GOLDTL_BufferLock)(void*, int, int, void**, int);
typedef void (__stdcall *GOLDTL_BufferUnlock)(void*);

typedef struct GOLDTL_BufferVtbl {
	char pad_00[0x2c];
	GOLDTL_BufferLock Lock;     /* 0x2c */
	GOLDTL_BufferUnlock Unlock; /* 0x30 */
} GOLDTL_BufferVtbl;

typedef struct GOLDTL_TerrainVertex {
	float x;                    /* 0x00 */
	float y;                    /* 0x04 */
	float z;                    /* 0x08 */
	unsigned long diffuse;      /* 0x0c */
	float u;                    /* 0x10 */
	float v;                    /* 0x14 */
} GOLDTL_TerrainVertex;

typedef struct GOLDTL_TileUv {
	float u;                    /* 0x00 */
	float du;                   /* 0x04 */
	float v;                    /* 0x08 */
	float dv;                   /* 0x0c */
} GOLDTL_TileUv;

#include "Develop/DieGildeAddOn/game/game_data.h"
extern unsigned char g_6b7ff9;

/* ADDRESS: GOLDTL 0x00457f40 */
int __cdecl d3_BuildShadowPatchFromHeightGrid(void* vb, void* ib, int* rect, int stride, int base,
	float* offset, float* scale, GOLDTL_TileUv* uv, unsigned long diffuse)
{
	GOLDTL_BufferVtbl* ops;

	void* verts;
	void* idxs;
	int count;
	int w;
	int h;
	int x;
	int y;
	int i;
	int j;
	int height;
	int h0;
	int h1;
	int h2;
	int h3;
	int th;
	float fx;
	float fy;
	float fz;
	float sx;
	float su;
	float u2;

	verts = 0;
	idxs = 0;
	count = 0;
	w = rect[1] - rect[0];
	h = rect[3] - rect[2];
	ops = *(GOLDTL_BufferVtbl**) vb;
	ops->Lock(vb, 0, (h + 1) * (w + 1) * 0x18, &verts, 0x2000);
	ops = *(GOLDTL_BufferVtbl**) ib;
	ops->Lock(ib, 0, h * w * 0xc, &idxs, 0x2000);
	if (verts == 0) {
		goto cleanup;
	}
	if (idxs == 0) {
		goto cleanup;
	}

	fx = (float) rect[0] * scale[0] + offset[0];
	fy = (g_6b7ff9 ? 2.5f : 1.5f) + offset[1];
	y = rect[2];
	fz = (float) y * scale[2] + offset[2];
	u2 = uv->v;

	while (y <= rect[3]) {
		x = rect[0];
		sx = fx;
		su = uv->u;
		while (x <= rect[1]) {
			height = *(unsigned char*) (base + y * stride + x);
			((GOLDTL_TerrainVertex*) verts)->x = sx;
			((GOLDTL_TerrainVertex*) verts)->y = (float) height * scale[1] + fy;
			((GOLDTL_TerrainVertex*) verts)->z = fz;
			((GOLDTL_TerrainVertex*) verts)->diffuse = diffuse;
			((GOLDTL_TerrainVertex*) verts)->u = su;
			((GOLDTL_TerrainVertex*) verts)->v = u2;
			verts = (GOLDTL_TerrainVertex*) verts + 1;
			sx += scale[0];
			su += uv->du;
			x++;
		}
		fz += scale[2];
		u2 += uv->dv;
		y++;
	}

	ops = *(GOLDTL_BufferVtbl**) vb;
	ops->Unlock(vb);
	verts = 0;
	th = (int) (25.0f / scale[1]);

	i = 0;
	while (i < h) {
		j = 0;
		if (w > 0) {
			do {
				h0 = *(unsigned char*) (base + (rect[2] + i) * stride + rect[0] + j);
				h1 = *(unsigned char*) (base + (rect[2] + i) * stride + rect[0] + j + 1);
				h2 = *(unsigned char*) (base + (rect[2] + i + 1) * stride + rect[0] + j);
				if (abs(h0 - h1) <= th && abs(h0 - h2) <= th
					&& abs(h1 - h2) <= th) {
					((unsigned short*) idxs)[0] = (unsigned short) (i * (w + 1) + j);
					((unsigned short*) idxs)[1] = (unsigned short) (i * (w + 1) + j + 1);
					((unsigned short*) idxs)[2] = (unsigned short) ((i + 1) * (w + 1) + j);
					idxs = (char*) idxs + 6;
					count++;
				}
				h3 = *(unsigned char*)(base + (rect[2] + i + 1) * stride + rect[0] + j + 1);
				if (abs(h3 - h1) <= th && abs(h3 - h2) <= th
					&& abs(h1 - h2) <= th) {
					((unsigned short*) idxs)[0] = (unsigned short) (i * (w + 1) + j + 1);
					((unsigned short*) idxs)[1] = (unsigned short) ((i + 1) * (w + 1) + j + 1);
					((unsigned short*) idxs)[2] = (unsigned short) ((i + 1) * (w + 1) + j);
					idxs = (char*) idxs + 6;
					count++;
				}
				j++;
			} while (j < w);
		}
		i++;
	}

	ops = *(GOLDTL_BufferVtbl**) ib;
	ops->Unlock(ib);
	idxs = 0;
cleanup:
	if (verts != 0) {
		ops = *(GOLDTL_BufferVtbl**) vb;
		ops->Unlock(vb);
	}
	if (idxs != 0) {
		ops = *(GOLDTL_BufferVtbl**) ib;
		ops->Unlock(ib);
	}
done:
	return count;
}
