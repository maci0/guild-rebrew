/* Terrain patch builder (one-cell step): locks a vertex buffer (24-byte
 * vertices) and an index buffer, fills both from the height grid, and
 * skips triangles whose corner heights differ by more than a scale-derived
 * threshold.  Returns the number of triangles written. */

#include <stdlib.h>

typedef int (__stdcall *GOLDTL_BufferLock)(void*, int, int, void**, int);
typedef void (__stdcall *GOLDTL_BufferUnlock)(void*);

typedef struct GOLDTL_BufferVtbl {
	char pad_00[0x2c];
	GOLDTL_BufferLock Lock;     /* 0x2c */
	GOLDTL_BufferUnlock Unlock; /* 0x30 */
} GOLDTL_BufferVtbl;

typedef struct GOLDTL_TerrainVertex {
	float x;                    /* 0x00 */
	float y;                    /* 0x04 */
	float z;                    /* 0x08 */
	unsigned long diffuse;      /* 0x0c */
	float u;                    /* 0x10 */
	float v;                    /* 0x14 */
} GOLDTL_TerrainVertex;

typedef struct GOLDTL_TileUv {
	float u;                    /* 0x00 */
	float du;                   /* 0x04 */
	float v;                    /* 0x08 */
	float dv;                   /* 0x0c */
} GOLDTL_TileUv;

extern float g_6629b0;
extern float g_662acc;
extern float g_662da8;
extern unsigned char g_6b7ff9;

/* ADDRESS: GOLDTL 0x00457f40 */
int __cdecl fcn_00457f40(void* vb, void* ib, int* rect, int stride, int base,
	float* offset, float* scale, GOLDTL_TileUv* uv, unsigned long diffuse)
{
	GOLDTL_BufferVtbl* ops;
	GOLDTL_TerrainVertex* v;
	unsigned short* idx;
	unsigned char* tile;
	void* verts;
	void* idxs;
	int count;
	int w;
	int h;
	int x;
	int y;
	int i;
	int j;
	int height;
	int h0;
	int h1;
	int h2;
	int h3;
	int th;
	float fx;
	float fy;
	float fz;
	float sx;
	float su;
	float u2;

	verts = 0;
	idxs = 0;
	count = 0;
	w = rect[1] - rect[0];
	h = rect[3] - rect[2];
	ops = *(GOLDTL_BufferVtbl**) vb;
	ops->Lock(vb, 0, (h + 1) * (w + 1) * 0x18, &verts, 0x2000);
	ops = *(GOLDTL_BufferVtbl**) ib;
	ops->Lock(ib, 0, w * h * 0xc, &idxs, 0x2000);
	if (verts == 0) {
		return count;
	}
	if (idxs == 0) {
		ops = *(GOLDTL_BufferVtbl**) vb;
		ops->Unlock(vb);
		return count;
	}

	fx = (float) rect[0] * scale[0] + offset[0];
	fy = offset[1] + (g_6b7ff9 ? g_6629b0 : g_662acc);
	y = rect[2];
	fz = (float) y * scale[2] + offset[2];
	u2 = uv->v;
	v = (GOLDTL_TerrainVertex*) verts;
	while (y <= rect[3]) {
		tile = (unsigned char*) (base + y * stride);
		x = rect[0];
		sx = fx;
		su = uv->u;
		while (x <= rect[1]) {
			height = tile[x];
			v->x = sx;
			v->y = (float) height * scale[1] + fy;
			v->z = fz;
			v->diffuse = diffuse;
			v->u = su;
			v->v = u2;
			v++;
			sx += scale[0];
			su += uv->du;
			x++;
		}
		tile += stride;
		fz += scale[2];
		u2 += uv->dv;
		y++;
	}

	ops = *(GOLDTL_BufferVtbl**) vb;
	ops->Unlock(vb);
	verts = 0;
	th = (int) (g_662da8 / scale[1]);

	i = 0;
	while (i < h) {
		j = 0;
		if (w > 0) {
			do {
				tile = (unsigned char*) (base + (rect[2] + i) * stride
					+ rect[0] + j);
				h0 = tile[0];
				h1 = tile[1];
				h2 = tile[stride];
				if (abs(h0 - h1) <= th && abs(h0 - h2) <= th
					&& abs(h1 - h2) <= th) {
					idx = (unsigned short*) idxs;
					idx[0] = (unsigned short) (i * (w + 1) + j);
					idx[1] = (unsigned short) (i * (w + 1) + j + 1);
					idx[2] = (unsigned short) ((i + 1) * (w + 1) + j);
					idxs = (char*) idxs + 6;
					count++;
				}
				h3 = tile[stride + 1];
				if (abs(h3 - h1) <= th && abs(h3 - h2) <= th
					&& abs(h1 - h2) <= th) {
					idx = (unsigned short*) idxs;
					idx[0] = (unsigned short) (i * (w + 1) + j + 1);
					idx[1] = (unsigned short) ((i + 1) * (w + 1) + j + 1);
					idx[2] = (unsigned short) ((i + 1) * (w + 1) + j);
					idxs = (char*) idxs + 6;
					count++;
				}
				j++;
			} while (j < w);
		}
		i++;
	}

	ops = *(GOLDTL_BufferVtbl**) ib;
	ops->Unlock(ib);
	idxs = 0;
	if (verts != 0) {
		ops = *(GOLDTL_BufferVtbl**) vb;
		ops->Unlock(vb);
	}
	if (idxs != 0) {
		ops = *(GOLDTL_BufferVtbl**) ib;
		ops->Unlock(ib);
	}
	return count;
}
