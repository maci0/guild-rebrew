"""Insert intra-TU data lead pads so each named global lands at its reference VA.

Data layout is a concatenation of TU contributions in link order. `converge`
adjusts only the first symbol of each TU; symbols after it drift by the size
difference of everything before them in the same TU. This pass walks the link
order, measures every symbol's current VA from the link map, and inserts a
reference-byte pad before the definition that is early, so it and its successors
move to their reference addresses.

    uv run scripts/gen_data_lead.py 0x4000
"""

import json
import re
import sys
import tomllib
from pathlib import Path

sys.path.insert(0, str(Path('/home/maci/Desktop/Projects/relumea/repos/rebrew/src')))
from rebrew.data_layout import (_find_definition, data_raw_from_binary,
                                layout_geometry)
from rebrew.utils import atomic_write_text, read_source_text

ROOT = Path(__file__).resolve().parents[1]
CAP = int(sys.argv[1], 0) if len(sys.argv) > 1 else 0x4000
MANIFEST = ROOT / '.scratch/organize/dlead2-manifest.json'
BUILD = ROOT / 'build-goldtl-audit'

mapfile = (BUILD / 'Europa1400Gold_TL.map').read_text(errors='replace')
actual: dict[str, int] = {}
obj_of: dict[str, str] = {}
# The map lists data symbols as ` 0003:<offset> <name> <absVA> <object>`; the
# ` 0003:<offset> <size>H <section> DATA` rows describe the sections themselves
# and carry no absolute address, so they must not be parsed as symbols.
for m in re.finditer(
    r'^ 0003:[0-9a-f]{8}\s+(\S+)\s+([0-9a-f]{8})\s+(\S+)\s*$', mapfile, re.M
):
    name = m.group(1).lstrip('_')
    actual[name] = int(m.group(2), 16)
    obj_of[name] = m.group(3)

store = tomllib.loads((ROOT / 'rebrew-data.toml').read_text())
rows: dict[str, dict[str, object]] = {}
for key, row in store.items():
    if not key.startswith('GOLDTL.') or not isinstance(row, dict) or not row.get('name'):
        continue
    rows[str(row['name'])] = {
        'va': int(key.split('.', 1)[1], 16),
        'file': row.get('file'),
        'section': row.get('section'),
    }

order: list[str] = []
for rsp in sorted((BUILD / 'CMakeFiles/europa1400gold_tl.dir').glob('objects*.rsp')):
    for token in rsp.read_text().split():
        if token.lower().endswith('.obj') and 'europa1400gold_tl.dir/' in token:
            order.append(token.split('europa1400gold_tl.dir/', 1)[1][:-4])

data_base, raw_end, _ = layout_geometry(ROOT / 'rebrew-project.toml', target='Europa1400Gold_TL.exe')
orig = data_raw_from_binary(ROOT / 'original/Europa1400Gold_TL.exe')
manifest = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else []
known = {entry['name'] for entry in manifest}

by_source: dict[str, list[tuple[int, str]]] = {}
for name, meta in rows.items():
    if name not in actual or meta['section'] not in ('.data', '.bss'):
        continue
    source = meta['file']
    if not source or not (ROOT / str(source)).is_file():
        continue
    by_source.setdefault(str(source), []).append((int(meta['va']), name))

added = 0
for source in order:
    if source not in by_source:
        continue
    text, encoding = read_source_text(ROOT / source)
    changed = False
    for expected, name in sorted(by_source[source]):
        needed = expected - actual[name]
        if needed <= 0 or needed > CAP:
            continue
        pad_name = f"_dlead2_{re.sub(r'[^A-Za-z0-9]', '_', name)}"
        if pad_name in known:
            continue
        found = _find_definition(text, name)
        if found is None:
            continue
        start = found[0]
        if expected + (0) <= raw_end and expected - needed >= data_base:
            off = (expected - needed) - data_base
            data = orig[off:off + needed]
            if len(data) != needed:
                data = bytes(needed)
            decl = (
                '/* Layout scaffolding: shifts this global and the rest of this TU\n'
                ' * to their reference VAs. Generated by the data lead pass. */\n'
                f"unsigned char {pad_name}[{needed}] = {{\n"
                + ",\n".join(f"    0x{b:02x}" for b in data)
                + "\n};\n"
            )
        else:
            decl = (
                '/* Layout scaffolding: shifts this global and the rest of this TU\n'
                ' * to their reference VAs. Generated by the data lead pass. */\n'
                f"unsigned char {pad_name}[{needed}];\n"
            )
        text = text[:start] + decl + text[start:]
        manifest.append({'file': source, 'name': pad_name, 'size': needed})
        known.add(pad_name)
        changed = True
        added += 1
    if changed:
        atomic_write_text(ROOT / source, text, encoding=encoding)
MANIFEST.write_text(json.dumps(manifest, indent=1))
print('added', added, 'pads, total', len(manifest))
