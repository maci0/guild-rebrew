#!/usr/bin/env python3
"""Rewrite the CURRENT STATE table in docs/TODO.md from a gate run's output.

Why this exists (round 238).  That table has a heading saying "Live numbers are
`scripts/gate.sh` defaults", and it has gone stale **twice** in this session --
once found in round 209 (verify 258, residue 38, raw-link `.data` 21,481 against
live 262, 0 and 0) and again in round 238 (raw-link imports "15 entries differ"
after round 225 made them match, and a gap of 41,619 against the measured
41,565).  Correcting it by hand fixes an instance; **generating it fixes the
class**, which is the same lesson as the gate's own checks.

Reads the gate's output on stdin, writes the block between the markers.  Called
by `scripts/gate.sh` at the end of a run; safe to run by hand:

    bash scripts/gate.sh 2>&1 | python3 scripts/update_state_table.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "TODO.md"
BEGIN = "<!-- CURRENT-STATE:BEGIN -->"
END = "<!-- CURRENT-STATE:END -->"


def grab(text: str, pattern: str, default: str = "?") -> str:
    m = re.search(pattern, text)
    return m.group(1).strip() if m else default


def main() -> int:
    log = sys.stdin.read()
    verify = grab(log, r"Verification: (\d+/\d+) passed")
    residue = grab(log, r"residue (\d+), baseline (\d+) held")
    residue = residue.split(",")[0].strip() if residue != "?" else "?"
    data = grab(log, r"raw-link \.data (\d+), baseline")
    reloc = grab(log, r"missing (\d+), extra (\d+) -- baseline")
    if reloc != "?":
        m = re.search(r"missing (\d+), extra (\d+)", log)
        reloc = "%s / %s" % (m.group(1), m.group(2)) if m else reloc
    gap = grab(log, r"OBJECTIVE GAP: (\d+) bytes")
    decomp = grab(log, r"of which: ([\d,]+ differing bytes in the common prefix, [\d,]+ bytes of size shortfall)")
    cov = grab(log, r"postlink layout-map coverage: ([0-9/]+ layout-map entries validate \([0-9.]+%)")
    short = grab(log, r"(\d+ function\(s\) are SHORTER than the binary's function \([0-9]+ bytes)")
    imports = ("matches" if "raw link imports match the reference"
               else "differs" if "raw-link import table differs" in log else "?")
    build = grab(log, r"cmake exit: (\d+)")

    rows = [
        ("verify `passed`", verify, "gate's `BASELINE`"),
        ("`.text` residue", residue, "gate's `RESIDUE_BASELINE`"),
        ("raw-link `.data` divergence", data, "gate's `DATA_BASELINE`"),
        ("relocation records missing / extra", reloc, "not measured; reloc_set_check.py removed"),
        ("raw-link import table", imports, "gate, round 210"),
        ("OBJECTIVE GAP (raw link vs reference)", gap, "gate's `OBJECTIVE_BASELINE`"),
        ("...of which", decomp, "gate's decomposition"),
        ("postlink layout-map coverage", cov, "gate -- **floor is 90%**"),
        ("annotations shorter than the binary", short, "`rebrew verify --json`"),
        ("`cmake --build` exit", build, "gate's build step"),
    ]
    body = ["| Quantity | Value | Source |", "|---|---|---|"]
    body += ["| %s | **%s** | %s |" % (a, b, c) for a, b, c in rows]
    block = "\n".join([
        BEGIN,
        "<!-- generated by scripts/update_state_table.py -- do not hand-edit -->",
        "",
        *body,
        "",
        END,
    ])

    text = DOC.read_text()
    # The markers must be anchored to their own line.  Matching them anywhere made
    # this script eat the prose around it: a round note that QUOTES the marker
    # strings was treated as a second marker pair, and everything between the
    # quoted open and close markers -- including the paragraph explaining the fix
    # -- was replaced by the table (found and repaired in round 242).
    pattern = r"(?m)^" + re.escape(BEGIN) + r"$.*?^" + re.escape(END) + r"$"
    if re.search(pattern, text, flags=re.S):
        text = re.sub(pattern, block, text, flags=re.S)
    else:
        text = text.replace("## CURRENT STATE\n", "## CURRENT STATE\n\n" + block + "\n", 1)
    DOC.write_text(text)
    print("state table regenerated: verify %s, gap %s, imports %s" % (verify, gap, imports))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
