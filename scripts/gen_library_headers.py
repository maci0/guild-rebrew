"""Rewrite every src/library_*.h as a catalog of the LIBRARY rows that name it.

rebrew reads library identities from rebrew-functions.toml by file path; a header body is
documentation only and is never compiled. Each header lists its rows as
`// MODULE 0xVA SIZE SYMBOL`, sorted by module and address (SIZE `n/a` when the row has
none). A header no row names is deleted. Run after `rebrew library adopt`,
`rebrew source rehome` or any other change to LIBRARY rows.
"""

from collections import defaultdict
from pathlib import Path

from rebrew.metadata.functions import load_metadata

TITLES = {
    "library_libcmt.h": "LIBCMT, the MSVC 6.0 SP5 multithreaded static C runtime (server.dll, Europa1400Gold_TL.exe)",
    "library_libc.h": "LIBC, the MSVC 6.0 SP5 single-threaded static C runtime (Europa1400Gold.exe)",
    "library_d3dx8.h": "d3dx8.lib, the DirectX 8 D3DX static library",
    "library_lua50.h": "Lua 5.0",
    "library_imports.h": "import thunks the linker emits for DLL imports",
}


def project_root() -> Path:
    here = Path(__file__).resolve()
    for parent in here.parents:
        if (parent / "rebrew-project.toml").exists():
            return parent
    raise SystemExit("rebrew-project.toml not found above " + str(here))


def main() -> None:
    root = project_root()
    rows: dict[str, list[tuple[str, int, str, str]]] = defaultdict(list)
    for (module, va), row in load_metadata(str(root), deepcopy=False).items():
        file = row.get("file") or ""
        if row.get("kind") == "LIBRARY" and file.startswith("src/library_") and file.endswith(".h"):
            size = row.get("size")
            rows[file].append((module, va, str(size) if size else "n/a", row.get("symbol") or row.get("name") or "n/a"))
    for header in sorted((root / "src").glob("library_*.h")):
        if f"src/{header.name}" not in rows:
            header.unlink()
            print("deleted", header.name)
    for file, entries in sorted(rows.items()):
        name = Path(file).name
        title = TITLES.get(name, name.removeprefix("library_").removesuffix(".h").upper())
        lines = [
            f"/* {title}.",
            " * Generated by scripts/gen_library_headers.py from the LIBRARY rows in",
            " * rebrew-functions.toml. The linker supplies these bodies; nothing here is compiled.",
            " * Columns: module, address, size in bytes, native symbol. */",
            "",
        ]
        lines += [f"// {m} 0x{va:08x} {size} {sym}" for m, va, size, sym in sorted(entries)]
        (root / file).write_text("\n".join(lines) + "\n")
        print(f"{name}: {len(entries)} rows")


if __name__ == "__main__":
    main()
