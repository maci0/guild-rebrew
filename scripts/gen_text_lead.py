"""Adjust one .text lead pad per object boundary to remove placement deficits.

A body that compiles shorter or longer than its reference extent leaves every
later object early or late; the link map measures that. This pass writes a
`#pragma data_seg(".text")` filler at the end of the previous TU, sized to the
measured deficit, so the next object starts where its first metadata row says.
An existing pad is resized, not duplicated: a second pass after a layout change
must be able to shrink or grow the pad the first pass wrote.

    uv run scripts/gen_text_lead.py 0x2000
"""

import json
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MAP = ROOT / 'build-goldtl-audit/Europa1400Gold_TL.map'
OBJDIR = ROOT / 'build-goldtl-audit/CMakeFiles/europa1400gold_tl.dir'
MAX_PAD = int(sys.argv[1], 0) if len(sys.argv) > 1 else 0x800

mapfile = MAP.read_text(errors='replace')
first_by_obj = {}
for m in re.finditer(r'^ 0001:[0-9a-f]{8}\s+(\S+)\s+([0-9a-f]{8})\s+f\s+(\S+)$', mapfile, re.M):
    obj = Path(m.group(3)).name
    va = int(m.group(2), 16)
    first_by_obj[obj] = min(first_by_obj.get(obj, va), va)

rows = tomllib.loads((ROOT / 'rebrew-functions.toml').read_text())
expected = {}
for key, row in rows.items():
    if not key.startswith('GOLDTL.') or not isinstance(row, dict) or not row.get('name'):
        continue
    path = row.get('file')
    if path:
        va = int(key.split('.', 1)[1], 16)
        expected[path] = min(expected.get(path, va), va)

order = []
for rsp in sorted(OBJDIR.glob('objects*.rsp')):
    for token in rsp.read_text().split():
        if token.lower().endswith('.obj') and 'europa1400gold_tl.dir/' in token:
            order.append(token.split('europa1400gold_tl.dir/', 1)[1][:-4])


def pad_name(prev: str) -> str:
    return f"_tlead_{re.sub(r'[^A-Za-z0-9]', '_', Path(prev).stem)}"


def resize_pad(text: str, name: str, new_size: int) -> str:
    """Rewrite the pad array with new_size bytes, or append it when absent."""
    pattern = re.compile(
        r'/\* Layout scaffolding: shifts the next source object to its reference\n'
        r' \* VA\. 0x90 filler, not reconstruction\. Generated by the text lead pass\. \*/\n'
        r'#pragma data_seg\("\.text"\)\n'
        r'unsigned char ' + re.escape(name) + r'\[[^\]]*\] = \{[^}]*\};\n'
    )
    block = (
        '/* Layout scaffolding: shifts the next source object to its reference\n'
        ' * VA. 0x90 filler, not reconstruction. Generated by the text lead pass. */\n'
        '#pragma data_seg(".text")\n'
        f'unsigned char {name}[{new_size}] = {{\n'
        + ',\n'.join('    0x90' for _ in range(new_size))
        + '\n};\n'
    )
    if pattern.search(text):
        return pattern.sub(block, text)
    if not text.endswith('\n'):
        text += '\n'
    return text + block


shift = 0
changed = 0
manifest = []
for idx, source in enumerate(order):
    if source not in expected:
        continue
    obj = Path(source).name + '.obj'
    actual = first_by_obj.get(obj)
    if actual is None:
        continue
    needed = expected[source] - (actual + shift)
    if needed > MAX_PAD:
        break
    prev = order[idx - 1] if idx else None
    if prev is None or not (ROOT / prev).is_file():
        continue
    pad_path = ROOT / prev
    text = pad_path.read_text(errors='surrogateescape')
    name = pad_name(prev)
    existing = 0
    m = re.search(re.escape(name) + r'\[(\d+)\]', text)
    if m:
        existing = int(m.group(1))
    new_size = existing + needed
    if new_size < 0:
        new_size = 0
    if new_size == existing:
        continue
    if new_size == 0:
        # Remove the pad entirely.
        pattern = re.compile(
            r'/\* Layout scaffolding: shifts the next source object to its reference\n'
            r' \* VA\. 0x90 filler, not reconstruction\. Generated by the text lead pass\. \*/\n'
            r'#pragma data_seg\("\.text"\)\n'
            r'unsigned char ' + re.escape(name) + r'\[[^\]]*\] = \{[^}]*\};\n'
        )
        pad_path.write_text(pattern.sub('', text), errors='surrogateescape')
    else:
        pad_path.write_text(resize_pad(text, name, new_size), errors='surrogateescape')
    shift += new_size - existing
    changed += 1
    manifest.append({'file': prev, 'name': name, 'old': existing, 'new': new_size})
    if changed > 200:
        break

Path('.scratch/organize/tlead-manifest.json').write_text(json.dumps(manifest, indent=1))
print('changed', changed, 'shift', hex(shift))
