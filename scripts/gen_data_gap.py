#!/usr/bin/env python3
"""Generate the .data gap TU (src/server.dll/crt_region/data_gap.c).

Our game TUs emit ~0x3000 bytes of initialized .data (strings/statics); the
original's .data raw is 0xe000.  This TU declares the missing bytes
[raw_size : 0xe000], copied from the original, so the RAW link's .data rsz
reaches 0xe000 without post-processing.  Link it FIRST (after crt_imports)
via CMakeLists (see the _DATA_GAP block).

Usage:
    python3 scripts/gen_data_gap.py                 # default raw-size 0x3000
    python3 scripts/gen_data_gap.py --raw-size 0x3000 --out /tmp/data_gap.c
"""
import argparse
import struct
from pathlib import Path

PROJECT = Path(__file__).resolve().parent.parent
ORIG = PROJECT / "original/Server/server.dll"
DATA_RAW = 0xE000


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--raw-size",
        default="0x3000",
        help="current initialized .data raw size of the game TUs (measure from a raw link)",
    )
    ap.add_argument(
        "--out",
        default=str(PROJECT / "src/server.dll/crt_region/data_gap.c"),
        help="output TU path",
    )
    args = ap.parse_args()
    start = int(args.raw_size, 0)
    assert 0 <= start < DATA_RAW, f"raw-size {start:#x} outside [0, 0xe000)"

    d = open(ORIG, "rb").read()
    e = struct.unpack_from("<I", d, 0x3C)[0]
    n = struct.unpack_from("<H", d, e + 6)[0]
    optsz = struct.unpack_from("<H", d, e + 20)[0]
    sh = e + 24 + optsz
    data_ro = None
    for i in range(n):
        h = sh + i * 40
        if d[h:h + 8].rstrip(b"\0") == b".data":
            data_ro = struct.unpack_from("<I", d, h + 20)[0]
    assert data_ro is not None, "no .data section in original"

    blob = d[data_ro + start : data_ro + DATA_RAW]
    lines = [
        "/* data_gap.c — AUTO-GENERATED by scripts/gen_data_gap.py",
        " * Declares the original's raw .data bytes [%#x:0xe000] that our game"
        % start,
        " * TUs do not emit, so the raw link's .data rsz reaches 0xe000.",
        " * Content is the original's bytes; fix_data copies the reference",
        " * .data over it for byte identity.  Link FIRST (after crt_imports).",
        " * Regenerate with: python3 scripts/gen_data_gap.py",
        " */",
        f"// DATA: SERVER 0x{0x10027000 + start:x}",
        "#pragma pack(push, 1)",
        f"unsigned char g_data_restore_gap[0x{len(blob):x}] = {{",
    ]
    for i in range(0, len(blob), 16):
        chunk = blob[i : i + 16]
        lines.append("\t" + ",".join(f"0x{b:02x}" for b in chunk) + ",")
    lines.append("};")
    lines.append("#pragma pack(pop)")

    out = Path(args.out)
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out} ({len(blob):#x} gap bytes from [0x{start:x}:0x{DATA_RAW:x}])")


if __name__ == "__main__":
    main()
