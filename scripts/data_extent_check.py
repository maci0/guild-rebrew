#!/usr/bin/env python3
"""Flag .data/.rdata metadata entries whose declared extent crosses the next symbol.

An entry whose `va + size` runs past the next tracked VA is wrong by
construction: two objects cannot occupy the same bytes.  The check needs no
disassembly and no judgement, and it found two real defects (a 4-byte size on a
byte-wide field, twice) that three rounds of type-conflict analysis walked past
-- an entry can be internally wrong while agreeing with every other TU
(docs/measure-traps.md section 6, round 905).

Containment is not automatically a defect.  Two legitimate shapes produce a
crossing:

  * a generated blob that covers a whole raw gap, with named *views* inside it
    (data_restore.c's g_data_restore_gap contains g_alchemy_entity_table);
  * an alias declared as an offset into a larger array
    (g_crash_space is `#define g_crash_space (g_crashdump_tail_10027318 + 16)`).

But geometry alone cannot tell those from a wrong size: round 905's two real
defects were a 4-byte `int` size on a byte-wide field, which for a 1-byte
neighbour looks identical to containment.  So **every crossing is reported**,
classified by whether the *container* is a known gap blob, and anything else
needs a human to check whether the inner symbol is a view (`extern`-only or a
`#define`) or a real object.

Usage:
    .venv/bin/python scripts/data_extent_check.py [--json]
"""

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from rebrew.data_layout import estimate_type_size  # noqa: E402

SECTIONS = (".data", ".rdata")

# Containers whose whole purpose is to span a raw gap, with named views inside
# them.  Each is verified, not assumed:
#   g_data_restore_gap -- generated by `rebrew gen-layout --data-gap`; its own
#     header says it covers .data [0x4600:0xe000] and postlink copies the
#     reference bytes over it.  Spans 0x1002b600..0x10035000 = raw .data end.
#   g_crashdump_tail_10027318 -- spans 0x10027318..0x1002733c, the 36 bytes
#     of crash-log strings documented in EmitCrashModuleLine.c, which defines
#     g_crash_space/arrow/unknown as offsets into it.
# Anything crossing outside this list is reported even when the inner symbol
# looks like a view, because "looks like a view" cannot be decided from a name.
KNOWN_GAP_BLOBS = {
    "g_data_restore_gap",
    "g_crashdump_tail_10027318",
}


def load_rows(toml_path):
    import tomllib

    with open(toml_path, "rb") as fh:
        db = tomllib.load(fh)

    rows = []
    for key, val in db.items():
        if not isinstance(val, dict):
            continue
        if str(val.get("section") or "") not in SECTIONS:
            continue
        _, sep, addr = str(key).rpartition(".")
        if not sep:
            continue
        try:
            va = int(addr, 16)
        except ValueError:
            continue

        size = val.get("size")
        if size is None:
            # `verify --data` derives a size from the type; use the same fallback
            # so an entry with a type but no size still participates.
            type_str = str(val.get("type") or "")
            size = estimate_type_size(type_str) if type_str else 0
            origin = "type"
        else:
            try:
                size = int(size)
            except (TypeError, ValueError):
                size = 0
            origin = "size"

        if size <= 0:
            continue
        rows.append(
            {
                "va": va,
                "size": size,
                "name": str(val.get("name") or f"<{addr}>"),
                "type": str(val.get("type") or ""),
                "origin": origin,
            }
        )
    rows.sort(key=lambda r: r["va"])
    return rows


def section_bounds():
    """Reference section VA ranges, read from the binary rather than hardcoded.

    An entry can also be wrong by running past its own section's virtual extent,
    which no neighbour comparison catches when the entry is the last one.
    """
    import pefile

    ref = REPO / "original" / "Server" / "server.dll"
    if not ref.exists():
        return {}
    pe = pefile.PE(str(ref), fast_load=True)
    base = pe.OPTIONAL_HEADER.ImageBase
    bounds = {}
    for sec in pe.sections:
        name = sec.Name.rstrip(b"\x00").decode()
        lo = base + sec.VirtualAddress
        bounds[name] = (lo, lo + sec.Misc_VirtualSize)
    return bounds


def section_of(va, bounds):
    """Which reference section contains *va*, or None."""
    for name, (lo, hi) in bounds.items():
        if lo <= va < hi:
            return name
    return None


def classify(rows):
    """Split crossings into (contained, overlaps).

    Geometry alone is not enough to tell a legitimate view from a wrong size: a
    4-byte size on a byte-wide field swallows a 1-byte neighbour exactly the way
    a blob swallows a view.  So BOTH lists are reported and the caller must
    check the inner symbol.  `contained` is where round 905's two real defects
    hid when this function trusted geometry alone.
    """
    contained, overlaps = [], []
    for i in range(len(rows) - 1):
        cur, nxt = rows[i], rows[i + 1]
        end = cur["va"] + cur["size"]
        if end <= nxt["va"]:
            continue
        if end >= nxt["va"] + nxt["size"]:
            contained.append((cur, nxt, end))
        else:
            overlaps.append((cur, nxt, end))
    return contained, overlaps


def view_status(name, src_dir):
    """Is *name* a view onto other bytes, or an object that owns its own?

    Returns "view" only on positive evidence -- a `#define` naming it as an
    offset into something else.  Everything else is "owns".

    **An `extern` declaration is NOT evidence of a view.**  It is ambiguous:
    g_crash_newline is a `#define` (a real view), but g_stat_b_array is
    `extern unsigned char g_stat_b_array[]` in sim.c and is a *separate object*
    whose bytes merely happen to be near.  Treating `extern` as a view made this
    check miss g_entity_type_bytes, one of the two defects it exists to find
    (round 905), so the default is now "owns" and the caller must allowlist.
    """
    import re

    if not src_dir.exists():
        return "owns"

    define_pat = re.compile(
        r"^\s*#\s*define\s+" + re.escape(name) + r"\b\s*\(?[^)\n]*[+)]", re.M
    )
    for path in src_dir.rglob("*"):
        if path.suffix not in (".c", ".h"):
            continue
        try:
            text = path.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            continue
        if not re.search(r"\b" + re.escape(name) + r"\b", text):
            continue
        if define_pat.search(text):
            return "view"
    return "owns"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--json", action="store_true")
    ap.add_argument(
        "--toml",
        default=str(REPO / "src" / "rebrew-data.toml"),
        help="path to rebrew-data.toml",
    )
    args = ap.parse_args()

    rows = load_rows(args.toml)
    contained, overlaps = classify(rows)

    src_dir = REPO / "src" / "server.dll"
    # A crossing where the inner symbol OWNS storage is a real bug: two objects
    # claim the same bytes.  Where it is a view, the outer entry legitimately
    # covers those bytes and nothing is wrong.
    bugs = []
    for cur, nxt, end in contained + overlaps:
        if cur["name"] in KNOWN_GAP_BLOBS:
            continue  # verified container; its inner symbols are views by design
        if view_status(nxt["name"], src_dir) == "owns":
            bugs.append((cur, nxt, end))

    if args.json:
        print(
            json.dumps(
                {
                    "entries": len(rows),
                    "bugs": [
                        {
                            "va": hex(c["va"]),
                            "name": c["name"],
                            "type": c["type"],
                            "origin": c["origin"],
                            "size": c["size"],
                            "next_va": hex(n["va"]),
                            "next_name": n["name"],
                            "by": end - n["va"],
                        }
                        for c, n, end in bugs
                    ],
                    "views": [
                        {
                            "va": hex(c["va"]),
                            "name": c["name"],
                            "next_va": hex(n["va"]),
                            "next_name": n["name"],
                        }
                        for c, n, _ in contained + overlaps
                        if (c, n, _) not in bugs
                    ],
                },
                indent=2,
            )
        )
        return 1 if bugs else 0

    print(f"checked {len(rows)} sized .data/.rdata entries")

    # A last-in-section entry has no neighbour to cross, so check the section
    # extent as well.  Round 908: all 162 entries were inside their section.
    bounds = section_bounds()
    for row in rows:
        sec = section_of(row["va"], bounds)
        if sec is None:
            continue
        lo, hi = bounds[sec]
        if not (lo <= row["va"] < hi):
            continue
        if row["va"] + row["size"] > hi:
            print(
                f"\nBUG: {row['name']} @0x{row['va']:x} size={row['size']} "
                f"runs past {sec} end 0x{hi:x} by "
                f"0x{row['va'] + row['size'] - hi:x}"
            )
            return 1

    views = [(c, n, e) for c, n, e in contained + overlaps if (c, n, e) not in bugs]
    if views:
        print(f"\nviews inside a container ({len(views)}) -- inner symbol owns no bytes:")
        for cur, nxt, _ in views:
            print(
                f"  {cur['name']} @0x{cur['va']:x} +{cur['size']} "
                f"contains {nxt['name']} @0x{nxt['va']:x}"
            )

    if bugs:
        print(f"\nBUGS ({len(bugs)}) -- inner symbol owns storage, two objects claim it:")
        for cur, nxt, end in bugs:
            print(
                f"  {cur['name']} @0x{cur['va']:x} {cur['type']} "
                f"size={cur['size']} ({cur['origin']}) crosses {nxt['name']} "
                f"@0x{nxt['va']:x} by 0x{end - nxt['va']:x}"
            )
        return 1

    print("\nno entry claims bytes owned by another")
    return 0


if __name__ == "__main__":
    sys.exit(main())
