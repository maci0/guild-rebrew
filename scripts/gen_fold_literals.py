#!/usr/bin/env python3
"""Emit the C spellings of every member string COMDAT a build carries.

Why: msvc6 derives a string literal's `??_C@...` COMDAT name from its contents
and MSVC LINK folds COMDATs by name (`crt_region/rdata_fold.c`,
`docs/msvc6-link-layout.md` section 3).  To fold a member's copy, a TU of ours
has to reference the same literal - and the easiest way to get the contents is
to read them straight out of a build that still carries them (the split set
carries every member's strings).

Usage:
    python3 scripts/gen_fold_literals.py build/split_poc.map build/split_poc.dll \\
        > .scratch/litfold/many.c

The output is a `const char*` array, which lands in `.data` (referenced
literals never go to `.rdata`); the pointer array exists only to keep the
literals referenced.
"""

import re
import struct
import sys
from pathlib import Path

LINE = re.compile(r"^\s+([0-9a-f]{4}):([0-9a-f]{8})\s+(\S+)\s+([0-9a-f]{8})\s*(.*)$")


def section_bytes(path, name):
    data = Path(path).read_bytes()
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    count = struct.unpack_from("<H", data, pe + 6)[0]
    opt = pe + 24
    for i in range(count):
        off = opt + struct.unpack_from("<H", data, pe + 20)[0] + i * 40
        if data[off : off + 8].rstrip(b"\0") == name.encode():
            vs, _va, _rs, ro = struct.unpack_from("<IIII", data, off + 8)
            return data[ro : ro + vs]
    raise SystemExit(f"no {name} in {path}")


def escape(c):
    if c == 34:
        return '\\"'
    if c == 92:
        return "\\\\"
    if 32 <= c < 127:
        return chr(c)
    # octal: `\x` is greedy in msvc6, so two adjacent bytes would merge
    return "\\%03o" % c


def coff_sections(data):
    """[(name, bytes)] for a COFF object."""
    count = struct.unpack_from("<H", data, 2)[0]
    opt = struct.unpack_from("<H", data, 16)[0]
    out = []
    for i in range(count):
        off = 20 + opt + i * 40  # section table follows the 20-byte header
        name = data[off : off + 8].rstrip(b"\0").decode("latin1")
        size = struct.unpack_from("<I", data, off + 16)[0]
        ptr = struct.unpack_from("<I", data, off + 20)[0]
        out.append((name, data[ptr : ptr + size]))
    return out


def coff_symbols(data):
    """[(name, section-1-based, value)] for a COFF object."""
    symoff = struct.unpack_from("<I", data, 8)[0]
    nsym = struct.unpack_from("<I", data, 12)[0]
    strtab = data[symoff + nsym * 18 :]
    out = []
    for i in range(nsym):
        e = data[symoff + i * 18 : symoff + (i + 1) * 18]
        if e[:4] == b"\0\0\0\0":
            off = struct.unpack_from("<I", e, 4)[0]
            name = strtab[off:].split(b"\0")[0].decode("latin1")
        else:
            name = e.split(b"\0")[0].decode("latin1")
        value, secno, _typ, cls, _aux = struct.unpack_from("<IhHBB", e, 8)
        if cls == 2 and secno > 0:
            out.append((name, secno, value))
    return out


def literals_from_objects(directory):
    """Every `??_C@` symbol in a split-object set, as a C literal."""
    seen, out = set(), []
    for path in sorted(Path(directory).glob("*.obj")):
        data = path.read_bytes()
        try:
            secs = coff_sections(data)
            syms = coff_symbols(data)
        except struct.error:
            continue
        for name, secno, value in syms:
            if not name.startswith("??_C@") or secno > len(secs):
                continue
            # each `??_C@` section is exactly the literal plus its terminator,
            # so the section size is the string length - which is the only way
            # to recover a string whose first byte is NUL (a_map.obj's two).
            body = secs[secno - 1][1]
            if name.startswith("??_C@_1"):  # wide
                chars = body[:-2].decode("utf-16-le") if len(body) >= 2 else ""
                lit = 'L"' + "".join(escape(ord(c)) for c in chars) + '"'
            else:
                data = body[:-1] if body.endswith(b"\0") else body
                lit = '"' + "".join(escape(c) for c in data) + '"'
            if lit not in seen:
                seen.add(lit)
                out.append(lit)
    return out


# The literals only exist to win the COMDAT names; the reference has these
# bytes in .rdata, not .data.  ".data$zz" sorts after every plain .data
# contribution, so they stop displacing the library data that follows them.
DATA_SEG = '#pragma data_seg(".data$zz")'


def main():
    if sys.argv[1] == "--split-dir":
        out = literals_from_objects(sys.argv[2])
        print("/* generated by scripts/gen_fold_literals.py - every member string COMDAT */")
        print(DATA_SEG)
        print("const char* g_rdata_fold_refs[] = {")
        print("\n".join("\t" + lit + "," for lit in out))
        print("};")
        return
    map_path, dll_path = sys.argv[1], sys.argv[2]
    text = section_bytes(dll_path, ".rdata")
    seen, out = set(), []
    for line in Path(map_path).read_text(errors="replace").splitlines():
        m = LINE.match(line)
        if not m or int(m.group(1), 16) != 2:
            continue
        name = m.group(3)
        if not name.startswith("??_C@"):
            continue
        off = int(m.group(2), 16)
        if name.startswith("??_C@_1"):  # wide
            end = off
            while text[end : end + 2] != b"\0\0":
                end += 2
            lit = 'L"' + "".join(escape(ord(c)) for c in text[off:end].decode("utf-16-le")) + '"'
        else:
            end = text.index(b"\0", off)
            lit = '"' + "".join(escape(c) for c in text[off:end]) + '"'
        if lit in seen:
            continue
        seen.add(lit)
        out.append("\t" + lit + ",")
    print("/* generated by scripts/gen_fold_literals.py - every member string COMDAT */")
    print(DATA_SEG)
    print("const char* g_rdata_fold_refs[] = {")
    print("\n".join(out))
    print("};")


if __name__ == "__main__":
    main()
