"""Write src/bss_layout/bss_head.c and bss_late.c: the game's zero-initialized data at the reference's addresses.

Reference layout of the data section's zero-filled tail, in VA order (docs/msvc6-link-layout.md 5c):

    head   explicit .bss of the game objects, up to the first LIBCMT .bss
    crt    plain .bss of the LIBCMT members the link loads (not ours; left to the linker)
    late   game data allocated after the CRT's plain .bss
    commons  LIBCMT COMMON symbols (not ours)

LINK lays plain `.bss` sections out in load order and COMMON after them. The head object is on the command
line, so its section comes first; bss_late.c is built into a static library listed after LIBCMT, so its
section follows the CRT's. Both files define every variable explicitly (zero initializer, so the compiler
emits `.bss`, not COMMON) in reference order, with a byte pad wherever the reference has an alignment gap
or a variable the reference rows do not name. The pads are named `g_gap_<va>`: missing is missing.

Reference rows can overlap (a named field inside a larger named object). Each row becomes its own symbol
that ends where the next row starts, so the bytes of a large object are covered by the symbols and pads
that follow it. Code addresses these names as separate symbols, as before.
Re-run after rebrew-data.toml changes.
"""

import re
import tomllib
from pathlib import Path

# zlib's zutil.obj emits the empty string "" as a 1-byte .bss COMDAT, and the reference
# has it at 0x10034620, between the Error and m_alloc variables. The head is two objects
# so zutil.obj (ordered between them by first function VA) lands its literal there.
HEAD = (0x10034610, 0x10034620)
HEAD2 = (0x10034624, 0x10035498)
LATE = (0x10035878, 0x11766208)
PLACEHOLDER = re.compile(r"g_(before|alignment)|g_(data|bss)_section_tail")
# Declared types of the alias names, which have no row of their own.
ALIAS_TYPES = {"g_alloc_root_name": "int", "g_entity_end": "char[]"}
ELEMENT_SIZE = {"char": 1, "unsigned char": 1, "short": 2, "unsigned short": 2, "int": 4, "unsigned int": 4, "float": 4}
# Reference row name -> the name the code uses for the same address.
ALIASES: dict[str, str] = {
    "g_alloc_root": "g_alloc_root_name",
    "g_town_records": "g_entity_end",
}
# Objects the code reaches through a struct type: emitted whole, their field rows not split out.
WHOLE = {"g_download_state"}
SCALAR = {1: "char", 2: "short", 4: "int"}
ARRAY_ALIGN = 4


def project_root() -> Path:
    here = Path(__file__).resolve()
    for parent in here.parents:
        if (parent / "rebrew-project.toml").exists():
            return parent
    raise SystemExit("rebrew-project.toml not found above " + str(here))


def load_items(root: Path) -> list[dict]:
    rows = tomllib.loads((root / "rebrew-data.toml").read_text())
    items = [
        {"va": int(k[-8:], 16), "name": r["name"], "size": r.get("size", 0), "type": r.get("type", "")}
        for k, r in rows.items()
        if k.startswith("SERVER.0x") and isinstance(r, dict) and r.get("size", 0) and not PLACEHOLDER.match(r["name"])
    ]
    items.sort(key=lambda i: (i["va"], -i["size"]))
    return items


def split(items: list[dict], lo: int, hi: int) -> list[dict]:
    """Rows in [lo, hi) as consecutive allocations: a row that overlaps its successor ends where the successor starts."""
    rows = [i for i in items if lo <= i["va"] < hi]
    for whole in [i for i in rows if i["name"] in WHOLE]:
        rows = [i for i in rows if not whole["va"] < i["va"] < whole["va"] + whole["size"]]
    for here, nxt in zip(rows, rows[1:] + [{"va": hi}]):
        here["size"] = min(here["size"] or 1, nxt["va"] - here["va"])
        if here["name"] in ALIASES:
            here["name"] = ALIASES[here["name"]]
            here["type"] = ALIAS_TYPES[here["name"]]
    return rows


def alignment(item: dict) -> int:
    return item["size"] if item["size"] in SCALAR else ARRAY_ALIGN


def pad(cur: int, target: int) -> tuple[list[str], int]:
    """Definitions that advance cur to target without the compiler adding alignment of its own."""
    out: list[str] = []
    while cur < target and cur % ARRAY_ALIGN:
        out.append(f"char g_gap_{cur:08x} = 0;")
        cur += 1
    whole = (target - cur) // ARRAY_ALIGN * ARRAY_ALIGN
    if whole:
        out.append(f"char g_gap_{cur:08x}[{whole}] = {{0}};")
        cur += whole
    while cur < target:
        out.append(f"char g_gap_{cur:08x} = 0;")
        cur += 1
    return out, cur


def emit(allocs: list[dict], start: int, end: int, title: str) -> str:
    lines = [f"/* {title}. Generated by scripts/gen_bss_layout.py; do not edit. */", ""]
    cur = start
    for i, a in enumerate(allocs):
        if a["va"] % alignment(a):
            raise SystemExit(f"{a['name']} at {a['va']:#x} is not {alignment(a)}-aligned")
        gap, cur = pad(cur, a["va"])
        lines += gap
        if cur != a["va"]:
            raise SystemExit(f"{a['name']}: layout reached {cur:#x} past {a['va']:#x}")
        lines.append(definition(a))
        cur += a["size"]
    gap, cur = pad(cur, end)
    return "\n".join(lines + gap) + "\n"


def definition(item: dict) -> str:
    """A zero-initialized definition of *item* in its declared type, cut to its allocated size."""
    name, size, declared = item["name"], item["size"], item["type"].strip()
    if "(*)" in declared and size == 4:
        return f"{declared.replace('(*)', f'(*{name})', 1)} = 0;"
    if declared.endswith("]") and item["va"] % ARRAY_ALIGN == 0:
        base = declared[: declared.index("[")].strip()
        elem = ELEMENT_SIZE.get(base)
        if elem and size % elem == 0:
            return f"{base} {name}[{size // elem}] = {{0}};"
    elif declared and (declared.endswith("*") or ELEMENT_SIZE.get(declared) == size):
        return f"{declared} {name} = 0;"
    if size in SCALAR:
        return f"{SCALAR[size]} {name} = 0;"
    return f"char {name}[{size}] = {{0}};"


def main() -> None:
    root = project_root()
    items = load_items(root)
    out = root / "src/bss_layout"
    out.mkdir(exist_ok=True)
    head = split(items, *HEAD)
    head2 = split(items, *HEAD2)
    late = split(items, *LATE)
    (out / "bss_head.c").write_text(emit(head, HEAD[0], HEAD[1], "Game .bss before zutil's empty string"))
    (out / "bss_head2.c").write_text(emit(head2, HEAD2[0], HEAD2[1], "Game .bss up to the CRT's"))
    (out / "bss_late.c").write_text(emit(late, LATE[0], LATE[1], "Game .bss that follows the CRT's"))
    print(f"head {len(head)} + {len(head2)} objects, late {len(late)} objects")


if __name__ == "__main__":
    main()
